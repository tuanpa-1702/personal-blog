// One row per file in public/uploads. The files are the source of truth for what
// is servable; this table is the metadata the library UI needs (who uploaded it,
// when, how big, what it was originally called) which the filesystem cannot hold.
function insertMedia({ filename, originalName, mimeType, bytes, width, height, uploaderId, folderId = null }) {
  const info = db
    .prepare(
      `INSERT INTO media (filename, original_name, mime_type, bytes, width, height, uploader_id, folder_id)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`
    )
    .run(filename, originalName, mimeType, bytes, width, height, uploaderId, folderId);
  return getMedia(info.lastInsertRowid);
}

// The one projection every media read goes through - the library list, getMedia(),
// getMediaByFilename(). It carries deleted_at because callers guard on it:
// DELETE /api/media/:id answers 404 for a row already in the bin, and a projection
// without the column made that guard read `undefined` no matter what the row said,
// so a second delete fell through to trash() and came back a 500 instead.
const MEDIA_SELECT = `
  SELECT m.id, m.filename, m.original_name, m.mime_type, m.bytes, m.width, m.height,
         m.uploader_id, m.folder_id, m.created_at, m.deleted_at, u.name AS uploader_name,
         f.name AS folder_name
    FROM media m
    LEFT JOIN users u ON u.id = m.uploader_id
    LEFT JOIN media_folders f ON f.id = m.folder_id`;

function getMedia(id) {
  return db.prepare(`${MEDIA_SELECT} WHERE m.id = ?`).get(id);
}

function getMediaByFilename(filename) {
  return db.prepare(`${MEDIA_SELECT} WHERE m.filename = ?`).get(filename);
}

// Files already on disk that have no row - everything uploaded before this table
// existed. Adopted rather than hidden: they are servable and deletable either way,
// so leaving them out of the library would mean the library does not describe what
// is actually there. Runs once at boot.
function adoptOrphanFiles() {
  let names;
  try {
    names = fs.readdirSync(PUBLIC_UPLOAD_DIR);
  } catch {
    return 0;
  }
  const known = new Set(db.prepare('SELECT filename FROM media').all().map((r) => r.filename));
  const insert = db.prepare(
    `INSERT OR IGNORE INTO media (filename, original_name, mime_type, bytes, width, height, uploader_id, created_at)
     VALUES (?, ?, ?, ?, ?, ?, NULL, ?)`
  );

  let adopted = 0;
  const rows = [];
  for (const name of names) {
    if (known.has(name)) continue;
    const ext = path.extname(name).toLowerCase();
    if (!ALLOWED_EXT.includes(ext)) continue; // lost+found, stray files
    const full = path.join(PUBLIC_UPLOAD_DIR, name);
    let stat;
    try {
      stat = fs.statSync(full);
      if (!stat.isFile()) continue;
    } catch {
      continue;
    }
    const size = imageSize(readHead(full), ext);
    // The filename's timestamp prefix is the upload time for anything this app
    // wrote; mtime is the fallback for a file copied in by hand.
    const stamp = /^(\d{13})-/.exec(name);
    const when = stamp ? new Date(Number(stamp[1])) : stat.mtime;
    rows.push([
      name,
      name,
      MIME_BY_EXT[ext] || 'application/octet-stream',
      stat.size,
      size ? size.width : null,
      size ? size.height : null,
      when.toISOString().slice(0, 19).replace('T', ' '),
    ]);
    adopted += 1;
  }
  if (rows.length) {
    db.transaction(() => {
      for (const r of rows) insert.run(...r);
    })();
    // Adopted files get thumbnails like uploaded ones. Queued in the background:
    // a bulk sync of files copied in over SSH must not block the boot or the
    // sync request behind forty-eight resizes.
    for (const r of rows) thumbs.ensureThumb(r[0]).catch(() => {});
  }
  return adopted;
}

// Rows whose file has since vanished from disk - deleted over SSH, or lost with a
// restore. Cleared at boot so the library never shows an image that cannot load.
// Trashed rows are skipped ON PURPOSE: their file is not missing, it is in
// data/media-trash/, and reaping them would empty the bin within six hours.
function pruneMissingFiles() {
  const rows = db.prepare('SELECT id, filename FROM media WHERE deleted_at IS NULL').all();
  const gone = rows.filter((r) => !fs.existsSync(path.join(PUBLIC_UPLOAD_DIR, r.filename)));
  if (gone.length) {
    const del = db.prepare('DELETE FROM media WHERE id = ?');
    db.transaction(() => {
      for (const r of gone) del.run(r.id);
    })();
    // Thumbnails outlive the file check above (they sit in uploads/thumbs/), so
    // they are swept here too.
    for (const r of gone) removeEveryCopy(r.filename);
  }
  return gone.length;
}

