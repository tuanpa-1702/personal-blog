// How many posts reference this file, and which ones.
//
// A post can reference an image two ways: as its cover_image, or inside the
// content JSON (an image block's url, or an <img src> in a rich-text block). Both
// are matched on the filename rather than the full URL, so a reference written as
// a path and one written as an absolute URL to this site both count.
//
// Used to warn before a delete. The warning is advisory - the delete still goes
// ahead if the caller confirms - because an image can also be referenced from
// somewhere this query cannot see (an old draft, a page outside the app), so
// refusing outright would make some files impossible to remove.
function findUsage(filename) {
  const needle = `%${filename}%`;
  return db
    .prepare(
      `SELECT id, title, slug, status FROM posts
        WHERE cover_image LIKE ? OR content LIKE ?
        ORDER BY created_at DESC`
    )
    .all(needle, needle);
}

// Deletes the file and its row together. The row goes first inside a transaction
// so a failed unlink rolls it back - a row with no file is a broken thumbnail in
// the library, while a file with no row is invisible until the next boot adopts it.
// This is also the PURGE path for a trashed image, so the file is looked for in
// the bin as well as in the served tree.
function deleteMedia(id) {
  const row = getMedia(id);
  if (!row) return { error: 'Không tìm thấy ảnh.' };
  const served = resolveUpload(row.filename);
  if (!served) return { error: 'Tên file không hợp lệ.' };
  const inTrash = trashPathFor(served);
  const full = fs.existsSync(served) ? served : inTrash && fs.existsSync(inTrash) ? inTrash : served;

  let unlinked = false;
  try {
    db.transaction(() => {
      db.prepare('DELETE FROM media WHERE id = ?').run(id);
      if (fs.existsSync(full)) {
        fs.unlinkSync(full);
        unlinked = true;
      }
    })();
    // Every leftover copy goes with the row - in the served tree and in the bin.
    // A stray derivative is invisible but not harmless: adoptOrphanFiles would
    // never claim it, so it would sit forever.
    removeEveryCopy(row.filename);
  } catch (e) {
    return { error: 'Không xoá được ảnh trên máy chủ.' };
  }
  return { ok: true, unlinked, filename: row.filename };
}

// Total bytes and count, for the library header. Trashed images count for
// neither: the header describes the library, and the bin is not the library.
function mediaTotals() {
  const row = db
    .prepare('SELECT COUNT(*) AS count, COALESCE(SUM(bytes), 0) AS bytes FROM media WHERE deleted_at IS NULL')
    .get();
  return { count: row.count, bytes: row.bytes, freeDisk: freeDiskBytes() };
}


// ---------------------------------------------------------------- folders
//
// Nested to any depth. Three things need care and none of them is the tree itself:
//
//   * A cycle. Re-parenting a folder under its own descendant would detach that whole
//     subtree from the root - it would still exist, still be in the table, and be
//     unreachable from the UI forever. isDescendant() below is what refuses it.
//   * Deleting a folder must not delete the images in it. The subtree cascades
//     (media_folders.parent_id ON DELETE CASCADE) but the images are set to unfiled.
//     A wrongly-unfiled image is recoverable; a deleted file is not.
//   * A database created before the folder_id column exists has no FOREIGN KEY on it
//     (SQLite cannot add one with ALTER TABLE), so the code below never relies on
//     ON DELETE SET NULL firing - it clears the column itself.

// Folder names are shown as text and used in a breadcrumb; they are not filenames, so
// the only real constraints are length and not being blank. "/" is excluded because
// the breadcrumb joins on it.
const MAX_FOLDER_NAME = 60;

function validateFolderName(name) {
  const clean = String(name ?? '').trim();
  if (!clean) return { error: 'Tên thư mục không được để trống.' };
  if (clean.length > MAX_FOLDER_NAME) {
    return { error: `Tên thư mục quá dài (tối đa ${MAX_FOLDER_NAME} ký tự).` };
  }
  if (clean.includes('/')) return { error: 'Tên thư mục không được chứa dấu "/".' };
  return { name: clean };
}

function getFolder(id) {
  if (id === null || id === undefined || id === '') return null;
  return db.prepare('SELECT id, name, parent_id, created_at FROM media_folders WHERE id = ?').get(id);
}

// Every folder, plus how many images each holds DIRECTLY (not counting subfolders).
// One query rather than one per folder: the sidebar renders the whole tree at once.
function listFolders() {
  return db
    .prepare(
      `SELECT f.id, f.name, f.parent_id, f.created_at,
              (SELECT COUNT(*) FROM media m WHERE m.folder_id = f.id AND m.deleted_at IS NULL) AS media_count
         FROM media_folders f
         ORDER BY f.parent_id IS NOT NULL, f.parent_id, f.name COLLATE NOCASE`
    )
    .all();
}

// Root-to-folder chain, for the breadcrumb. Walks parents with a hard iteration cap:
// a cycle should be impossible (isDescendant refuses to create one) but a corrupt row
// must not hang a request.
function folderPath(id) {
  const chain = [];
  let current = getFolder(id);
  let guard = 0;
  while (current && guard++ < 64) {
    chain.unshift(current);
    current = getFolder(current.parent_id);
  }
  return chain;
}

// Is `candidateId` inside the subtree rooted at `folderId`? Also true when they are
// the same folder, since "move a folder into itself" is the same mistake.
function isDescendant(candidateId, folderId) {
  if (candidateId === null || candidateId === undefined) return false;
  if (Number(candidateId) === Number(folderId)) return true;
  let current = getFolder(candidateId);
  let guard = 0;
  while (current && guard++ < 64) {
    if (Number(current.id) === Number(folderId)) return true;
    current = getFolder(current.parent_id);
  }
  return false;
}

function createFolder(name, parentId) {
  const checked = validateFolderName(name);
  if (checked.error) return checked;

  const parent = parentId ? getFolder(parentId) : null;
  if (parentId && !parent) return { error: 'Thư mục cha không tồn tại.' };

  // UNIQUE(parent_id, name) does not constrain top-level rows, because SQLite treats
  // NULLs as distinct - so the duplicate check has to happen here for those.
  const clash = parent
    ? db
        .prepare('SELECT id FROM media_folders WHERE parent_id = ? AND name = ? COLLATE NOCASE')
        .get(parent.id, checked.name)
    : db
        .prepare('SELECT id FROM media_folders WHERE parent_id IS NULL AND name = ? COLLATE NOCASE')
        .get(checked.name);
  if (clash) return { error: 'Đã có thư mục cùng tên ở đây.' };

  const info = db
    .prepare('INSERT INTO media_folders (name, parent_id) VALUES (?, ?)')
    .run(checked.name, parent ? parent.id : null);
  return { folder: getFolder(info.lastInsertRowid) };
}

function renameFolder(id, name) {
  const folder = getFolder(id);
  if (!folder) return { error: 'Không tìm thấy thư mục.' };
  const checked = validateFolderName(name);
  if (checked.error) return checked;

  const clash =
    folder.parent_id === null
      ? db
          .prepare('SELECT id FROM media_folders WHERE parent_id IS NULL AND name = ? COLLATE NOCASE AND id != ?')
          .get(checked.name, id)
      : db
          .prepare('SELECT id FROM media_folders WHERE parent_id = ? AND name = ? COLLATE NOCASE AND id != ?')
          .get(folder.parent_id, checked.name, id);
  if (clash) return { error: 'Đã có thư mục cùng tên ở đây.' };

  db.prepare('UPDATE media_folders SET name = ? WHERE id = ?').run(checked.name, id);
  return { folder: getFolder(id) };
}

function moveFolder(id, newParentId) {
  const folder = getFolder(id);
  if (!folder) return { error: 'Không tìm thấy thư mục.' };

  const parentId =
    newParentId === null || newParentId === undefined || newParentId === '' ? null : Number(newParentId);
  if (parentId !== null && !getFolder(parentId)) return { error: 'Thư mục đích không tồn tại.' };
  // The check that matters: moving a folder into its own subtree would orphan
  // everything below it.
  if (parentId !== null && isDescendant(parentId, id)) {
    return { error: 'Không thể chuyển một thư mục vào chính nó hoặc vào thư mục con của nó.' };
  }

  const clash =
    parentId === null
      ? db
          .prepare('SELECT id FROM media_folders WHERE parent_id IS NULL AND name = ? COLLATE NOCASE AND id != ?')
          .get(folder.name, id)
      : db
          .prepare('SELECT id FROM media_folders WHERE parent_id = ? AND name = ? COLLATE NOCASE AND id != ?')
          .get(parentId, folder.name, id);
  if (clash) return { error: 'Thư mục đích đã có thư mục cùng tên.' };

  db.prepare('UPDATE media_folders SET parent_id = ? WHERE id = ?').run(parentId, id);
  return { folder: getFolder(id) };
}

// Every folder id in the subtree rooted at `id`, including `id`. Collected by walking
// the flat list rather than with a recursive CTE, so it behaves the same on the
// node:sqlite shim the tests use.
function subtreeIds(id) {
  const all = db.prepare('SELECT id, parent_id FROM media_folders').all();
  const byParent = new Map();
  for (const row of all) {
    const key = row.parent_id === null ? 'root' : String(row.parent_id);
    if (!byParent.has(key)) byParent.set(key, []);
    byParent.get(key).push(row.id);
  }
  const out = [];
  const stack = [Number(id)];
  let guard = 0;
  while (stack.length && guard++ < 10000) {
    const current = stack.pop();
    out.push(current);
    for (const child of byParent.get(String(current)) || []) stack.push(child);
  }
  return out;
}

// Deletes a folder and its whole subtree. Images are UNFILED, never deleted - the
// files stay on disk and stay in the library, they just lose their folder.
function deleteFolder(id) {
  const folder = getFolder(id);
  if (!folder) return { error: 'Không tìm thấy thư mục.' };

  const ids = subtreeIds(id);
  const placeholders = ids.map(() => '?').join(', ');
  let unfiled = 0;
  db.transaction(() => {
    unfiled = db
      .prepare(`UPDATE media SET folder_id = NULL WHERE folder_id IN (${placeholders})`)
      .run(...ids).changes;
    // Deleting the root of the subtree cascades the rest where the schema has the
    // foreign key; the explicit IN covers a database whose media table predates it.
    db.prepare(`DELETE FROM media_folders WHERE id IN (${placeholders})`).run(...ids);
  })();
  return { ok: true, deletedFolders: ids.length, unfiled };
}

// Moves images between folders. `folderId` null means unfile them. Only ids that
// exist are touched, and the count returned is what actually changed - so a caller
// sending a stale id learns that fewer moved than it asked for.
function moveMedia(mediaIds, folderId) {
  const ids = (Array.isArray(mediaIds) ? mediaIds : []).map(Number).filter(Number.isInteger);
  if (!ids.length) return { error: 'Chưa chọn ảnh nào.' };
  if (folderId !== null && !getFolder(folderId)) return { error: 'Thư mục đích không tồn tại.' };

  const placeholders = ids.map(() => '?').join(', ');
  // Trashed images are not in the library, so nothing in the UI can file them;
  // the filter keeps a hand-rolled request from reorganising the bin.
  const changes = db
    .prepare(`UPDATE media SET folder_id = ? WHERE deleted_at IS NULL AND id IN (${placeholders})`)
    .run(folderId, ...ids).changes;
  return { ok: true, moved: changes };
}

