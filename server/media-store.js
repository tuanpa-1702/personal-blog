// Media library: storage, validation and bookkeeping for uploaded images.
//
// Shared by routes/media.js (the library) and routes/upload.js (the avatar
// uploader), so the format checks and the filename rules exist in exactly one
// place. Everything that decides whether a file may be served lives here.
//
// WHY FILES ARE WRITTEN TO A TEMP DIRECTORY FIRST
// An admin upload has no size limit, so it cannot be buffered in memory the way
// the 8 MB path was - a multi-gigabyte file would take the process down. So every
// upload streams to `data/tmp-uploads/`, which is OUTSIDE public/, and is only
// moved into `public/uploads/` after its bytes have been checked. The security
// property that matters is unchanged: a file that is not an image is never
// reachable over HTTP, because it never enters the served directory at all.

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const db = require('./db');
// Thumbnails for the library grid. A leaf module (it requires nothing from this
// file), generated by ImageMagick when the server has it, silently inert when
// not - see server/thumbs.js.
const thumbs = require('./thumbs');

const PUBLIC_UPLOAD_DIR = path.join(__dirname, '..', 'public', 'uploads');
const DATA_DIR = path.join(__dirname, '..', 'data');
// Sibling of the database rather than a system temp dir, so the move into
// public/uploads is a rename within one filesystem instead of a copy - a 2 GB
// file would otherwise be read and rewritten in full.
const TMP_UPLOAD_DIR = path.join(DATA_DIR, 'tmp-uploads');
// Where a trashed image waits to be restored or purged. A sibling of the
// database rather than a subdirectory of public/uploads ON PURPOSE: everything
// under public/uploads is servable over HTTP and is swept by the two
// reconciliation passes below, both of which read "a file is in that directory"
// as "this image is live". Keeping the bin outside the served tree is what makes
// a trashed image unreachable by URL, and what stops adoptOrphanFiles() from
// re-adopting it as a brand-new ownerless row.
const MEDIA_TRASH_DIR = path.join(DATA_DIR, 'media-trash');

// The bin is NOT in this list: it needs a writability check rather than a mkdir,
// because "exists" and "this process may write into it" come apart on a server in
// a way that silently breaks every delete. See ensureTrashDir(), below.
for (const dir of [PUBLIC_UPLOAD_DIR, TMP_UPLOAD_DIR]) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

const ALLOWED_EXT = ['.jpg', '.jpeg', '.png', '.webp', '.gif'];

// Per-file ceiling for an `editor`, and for the avatar route every role can reach.
// Admins are exempt (see resolveLimits below) - that is the point of the library.
const EDITOR_MAX_FILE_BYTES = 8 * 1024 * 1024;
const EDITOR_MAX_UPLOADS_PER_HOUR = 40;

// The one limit an admin is still held to. SQLite writes its WAL to this same
// filesystem, so a full disk does not merely stop uploads - it stops the site
// being able to save a post, a comment or a login attempt. Refusing an upload is
// recoverable; a wedged database is not.
const MIN_FREE_DISK_BYTES = 1024 * 1024 * 1024; // 1 GB

// Magic bytes. The extension is caller-controlled, so it decides nothing on its
// own: a .jpg holding HTML would be served back from our own origin, which is how
// an "image" upload becomes stored XSS.
const SIGNATURES = [
  { ext: '.jpg', bytes: [0xff, 0xd8, 0xff] },
  { ext: '.png', bytes: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  { ext: '.gif', bytes: [0x47, 0x49, 0x46, 0x38] }, // GIF8
];

const MIME_BY_EXT = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
};

function sniffFormat(buf) {
  for (const sig of SIGNATURES) {
    if (sig.bytes.every((b, i) => buf[i] === b)) return sig.ext;
  }
  // WEBP is a RIFF container: "RIFF" .... "WEBP"
  if (buf.slice(0, 4).toString('latin1') === 'RIFF' && buf.slice(8, 12).toString('latin1') === 'WEBP') {
    return '.webp';
  }
  return null;
}

// Reads just the head of a file - enough for both the signature check and the
// dimension readers below, without loading a large image into memory.
function readHead(filePath, length = 65536) {
  const fd = fs.openSync(filePath, 'r');
  try {
    const buf = Buffer.alloc(length);
    const read = fs.readSync(fd, buf, 0, length, 0);
    return buf.subarray(0, read);
  } finally {
    fs.closeSync(fd);
  }
}

// ---------------------------------------------------------------- dimensions
//
// Width and height are read from the file header rather than by decoding the
// image: the library grid wants them for layout (and to warn about an image far
// too large for a post), and decoding a multi-megapixel JPEG to learn two numbers
// would cost more than the upload itself. A format this cannot parse simply has no
// dimensions recorded - the grid handles null.

function pngSize(buf) {
  // IHDR is always the first chunk: 8-byte signature, 4-byte length, "IHDR".
  if (buf.length < 24 || buf.toString('latin1', 12, 16) !== 'IHDR') return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function gifSize(buf) {
  if (buf.length < 10) return null;
  return { width: buf.readUInt16LE(6), height: buf.readUInt16LE(8) };
}

function jpegSize(buf) {
  // Walk the marker chain to the first Start-Of-Frame, which carries the size.
  let i = 2; // past SOI
  while (i + 9 < buf.length) {
    if (buf[i] !== 0xff) {
      i += 1;
      continue;
    }
    const marker = buf[i + 1];
    // Standalone markers carry no length field.
    if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
      i += 2;
      continue;
    }
    const length = buf.readUInt16BE(i + 2);
    // SOF0..SOF15, excluding the four that are not frame headers (DHT/JPG/DAC/RST).
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    i += 2 + length;
  }
  return null;
}

function webpSize(buf) {
  if (buf.length < 30) return null;
  const kind = buf.toString('latin1', 12, 16);
  // Lossy: VP8 bitstream, size at a fixed offset after the 3-byte start code.
  if (kind === 'VP8 ') {
    return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  }
  // Lossless: 14 bits each, packed across four bytes.
  if (kind === 'VP8L') {
    const bits = buf.readUInt32LE(21);
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
  }
  // Extended (animation, alpha): canvas size in the VP8X chunk, 24 bits each.
  if (kind === 'VP8X') {
    return {
      width: buf.readUIntLE(24, 3) + 1,
      height: buf.readUIntLE(27, 3) + 1,
    };
  }
  return null;
}

function imageSize(buf, ext) {
  try {
    if (ext === '.png') return pngSize(buf);
    if (ext === '.gif') return gifSize(buf);
    if (ext === '.jpg' || ext === '.jpeg') return jpegSize(buf);
    if (ext === '.webp') return webpSize(buf);
  } catch {
    // A truncated or unusual header is not a reason to reject an upload that
    // already passed the signature check - it only means no dimensions.
  }
  return null;
}

// ---------------------------------------------------------------- filenames

// Recovers the UTF-8 filename from what multer hands over.
//
// busboy - which multer 1.x uses - decodes a multipart filename as LATIN-1 unless
// told otherwise, and multer 1.x exposes no option to change it. Browsers send
// UTF-8, so a Vietnamese filename arrives mangled: "ảnh của tôi.png" becomes
// "áº£nh cá»§a tÃ´i.png". Re-encoding those characters back to bytes and decoding them
// as UTF-8 undoes exactly that transformation.
//
// Only applied when the result round-trips: a name that was already correct, or one
// whose bytes are not valid UTF-8, is left alone rather than corrupted by a second
// conversion.
function decodeOriginalName(name) {
  const raw = String(name || '');
  try {
    const bytes = Buffer.from(raw, 'latin1');
    const utf8 = bytes.toString('utf8');
    // A failed decode leaves U+FFFD; and if re-encoding does not reproduce the same
    // bytes then `raw` was not a latin1 view of UTF-8 in the first place.
    if (utf8.includes('�')) return raw;
    if (!Buffer.from(utf8, 'utf8').equals(bytes)) return raw;
    return utf8;
  } catch {
    return raw;
  }
}

// The stored name is generated, never derived from what the client sent: a
// caller-supplied name is a path-traversal and an overwrite waiting to happen
// ("../../server/db.js", or a second upload of "logo.png" replacing the first).
// The original name is kept in the database instead, for display only.
function generateFilename(ext) {
  return `${Date.now()}-${crypto.randomBytes(8).toString('hex')}${ext}`;
}

// Resolves a stored filename to its path on disk, refusing anything that is not a
// bare name inside public/uploads. `path.basename` alone would be enough for the
// generated names, but this is the function every delete and every read goes
// through, so it verifies rather than assumes.
function resolveUpload(filename) {
  const bare = path.basename(String(filename || ''));
  if (!bare || bare === '.' || bare === '..') return null;
  const full = path.join(PUBLIC_UPLOAD_DIR, bare);
  // Belt and braces: the prefix check catches anything basename() did not.
  if (!full.startsWith(PUBLIC_UPLOAD_DIR + path.sep)) return null;
  return full;
}

// ---------------------------------------------------------------- the trash bin

// Whether the bin is a directory this process may actually write into.
//
// "Exists" is not the same question, and on a server the two come apart in a way
// that breaks every delete at once: `sudo bash scripts/security-deploy.sh`
// requires this module as root, the mkdir in ensureTrashDir() then creates
// data/media-trash owned by root at 0755, and pm2 - running as an ordinary user,
// as that script itself insists it should - finds the directory already there and
// never questions it. From that moment every rename into the bin answers EACCES.
// Nothing else about the site changes: uploads work, posts save, the library
// lists, and the only symptom anywhere is one opaque sentence in the admin UI
// when somebody tries to delete an image.
//
// It is recoverable from inside the process, which is why this is code and not
// just a log line. Replacing a directory needs write permission on its PARENT,
// not on the directory itself, and data/ is writable by this process - SQLite is
// writing its WAL there. So an unusable bin that is EMPTY is renamed aside and
// rebuilt, owned by whoever is running. A bin holding anything is left strictly
// alone, because it may hold images an admin expects to restore, and only
// reported with the exact chown that fixes it.
const PERMISSION_CODES = ['EACCES', 'EPERM', 'EROFS'];

function runAsUser() {
  try {
    return os.userInfo().username;
  } catch {
    return null;
  }
}

function chownCommand(dir) {
  const who = runAsUser() || '<user-chạy-pm2>';
  return `sudo chown -R ${who} ${dir} && sudo chmod 700 ${dir}`;
}

// Writes and removes a scratch file in the bin. Returns the error that refused
// it, or null when the bin is usable. The probe is a dotfile with no image
// extension, so one left behind by a crash is invisible to both reconciliation
// passes - adoptOrphanFiles() filters on ALLOWED_EXT, and this directory is
// outside public/ altogether.
function probeTrashDir() {
  const probe = path.join(MEDIA_TRASH_DIR, `.probe-${process.pid}-${crypto.randomBytes(4).toString('hex')}`);
  try {
    fs.writeFileSync(probe, '');
  } catch (e) {
    return e;
  }
  try {
    fs.unlinkSync(probe);
  } catch {
    /* a probe that outlives the check costs one empty file */
  }
  return null;
}

function refuseTrashDir(err, what) {
  const code = (err && err.code) || 'UNKNOWN';
  console.error(
    `[media] ${what}: ${MEDIA_TRASH_DIR} (${code}${err && err.message ? `: ${err.message}` : ''}). ` +
      'Ảnh trong thư viện sẽ KHÔNG xoá được cho tới khi sửa xong. Chạy trên máy chủ: ' +
      chownCommand(MEDIA_TRASH_DIR)
  );
  return { code };
}

// The boot check, and the one moveToTrash()/restoreFromTrash() re-run after a
// refusal. Returns null when the bin is usable, { code } when it is not - so the
// module-level fault reads as a plain truthy test.
function ensureTrashDir() {
  try {
    fs.mkdirSync(MEDIA_TRASH_DIR, { recursive: true });
  } catch (e) {
    return refuseTrashDir(e, 'không tạo được thư mục thùng rác');
  }

  const err = probeTrashDir();
  if (!err) return null;
  if (!PERMISSION_CODES.includes(err.code)) return refuseTrashDir(err, 'không ghi được vào thùng rác');

  // Only an empty bin is ever replaced, and only for a permission answer: the
  // rebuild renames the directory away, and a non-empty one is somebody's pending
  // restore. A directory this process cannot even list is treated as non-empty -
  // guessing wrong there loses files.
  let entries;
  try {
    entries = fs.readdirSync(MEDIA_TRASH_DIR);
  } catch {
    return refuseTrashDir(err, 'không ghi được vào thùng rác, và cũng không đọc được để tự sửa');
  }
  if (entries.length) {
    return refuseTrashDir(err, 'không ghi được vào thùng rác (thư mục không rỗng nên không tự thay được)');
  }

  const aside = `${MEDIA_TRASH_DIR}.unwritable-${Date.now()}`;
  try {
    fs.renameSync(MEDIA_TRASH_DIR, aside);
    fs.mkdirSync(MEDIA_TRASH_DIR, { recursive: true });
  } catch (e) {
    return refuseTrashDir(e, 'không dựng lại được thùng rác');
  }
  const retry = probeTrashDir();
  if (retry) return refuseTrashDir(retry, 'thùng rác vừa dựng lại vẫn không ghi được');

  console.warn(
    `[media] data/media-trash cũ rỗng nhưng tiến trình này không ghi được (${err.code}) - đã dời nó sang ` +
      `${path.basename(aside)} và tạo thư mục mới thuộc về ${runAsUser() || 'tiến trình này'}. ` +
      'Xoá ảnh hoạt động trở lại, không cần khởi động lại. Thư mục cũ xoá được; nguyên nhân thường là ' +
      'script deploy từng chạy bằng sudo.'
  );
  return null;
}

// Set at boot, refreshed after any refusal. Refreshing is the point: an admin who
// runs the chown while the server is up should not also have to restart it before
// they can delete an image.
let trashDirFault = ensureTrashDir();

// Passive read of the last check, for a listing that runs on every scroll of the
// grid: it must not write a probe file per page.
function trashDirStatus() {
  return { writable: !trashDirFault, code: trashDirFault ? trashDirFault.code : null };
}

// Active: re-runs the check - healing an empty bin it can heal - and reports it.
// This is the one an admin action calls, so hitting "Đồng bộ" in the library both
// says whether the bin is broken and fixes the kind that is fixable from here.
function checkTrashDir() {
  trashDirFault = ensureTrashDir();
  return trashDirStatus();
}

// The sentence an admin sees, with the reason attached. The bare message was the
// whole of the bug report - it said a bin had refused and not why, and why is the
// only part anybody can act on. Deleting somebody else's image is admin-only, and
// a directory name plus an errno is not a secret worth keeping from the person
// who owns the server; the absolute path stays in the log.
function trashErrorMessage(base, e) {
  const code = (e && e.code) || '';
  if (PERMISSION_CODES.includes(code)) {
    return `${base} Máy chủ không có quyền ghi vào data/media-trash (${code}). Chạy: ${chownCommand('data/media-trash')}`;
  }
  if (code === 'ENOSPC') return `${base} Đĩa máy chủ đã đầy (${code}).`;
  return code ? `${base} (${code})` : base;
}

// Every path one upload occupies on disk: the original plus both derivatives.
// A derivative is only there once ImageMagick has made it, so callers treat a
// missing one as normal rather than as failure.
function filePaths(filename) {
  const out = [resolveUpload(filename)];
  for (const kind of Object.keys(thumbs.VARIANTS)) out.push(thumbs.pathFor(filename, kind));
  return out.filter(Boolean);
}

// The bin mirrors the layout under public/uploads - 'x.png' lands in
// data/media-trash/x.png, 'thumbs/x.jpg' in data/media-trash/thumbs/x.jpg - so a
// restore puts every piece back without having to remember where it came from.
function trashPathFor(full) {
  if (!full) return null;
  const rel = path.relative(PUBLIC_UPLOAD_DIR, full);
  if (!rel || rel.startsWith('..')) return null;
  return path.join(MEDIA_TRASH_DIR, rel);
}

// One move, by rename where the filesystem allows it and by copy+unlink where
// it does not: rename() refuses to cross devices (EXDEV), and public/uploads can
// sit on another mount from data/ - a bind mount for disk space, say - which
// makes the bin another device and every rename fail. The copy is the same move
// by hand, a little slower.
function moveOne(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  try {
    fs.renameSync(src, dest);
  } catch (e) {
    if (e.code !== 'EXDEV') throw e;
    fs.copyFileSync(src, dest);
    fs.unlinkSync(src);
  }
}

// Moves an upload and whichever derivatives exist into the bin. This is what
// makes a trashed image stop loading: the file leaves the served directory in
// the same request that sets deleted_at.
//
// A failure halfway through puts back whatever already moved: an image half in
// the bin would 404 some of its paths while its row still says live, which is
// worse than either honest state. The real errno goes to the log AND into the
// message an admin sees, because a bin that refuses needs a reason and the bare
// sentence gives nobody anything to act on.
function moveToTrash(filename, retried = false) {
  // A bin found unusable at boot is re-checked rather than assumed: the chown
  // that fixes it is something an admin runs while the server is up.
  if (trashDirFault) trashDirFault = ensureTrashDir();

  const done = [];
  const undo = () => {
    for (const [from, back] of done.reverse()) {
      try {
        moveOne(from, back);
      } catch {
        /* best effort: the bin keeping a copy is recoverable, a half image is not */
      }
    }
  };

  try {
    for (const full of filePaths(filename)) {
      if (!fs.existsSync(full)) continue;
      const dest = trashPathFor(full);
      if (!dest) {
        undo();
        return { error: 'Tên file không hợp lệ.' };
      }
      moveOne(full, dest);
      done.push([dest, full]);
    }
  } catch (e) {
    console.error('[media] không dời được ảnh vào thùng rác:', filename, e && e.code, e && e.message);
    undo();
    // A refusal about PERMISSION is the one kind this process may be able to undo
    // by itself - see ensureTrashDir(). Worth exactly one retry, and only after
    // everything that did move is back, so the retry starts from a whole image.
    if (!retried && PERMISSION_CODES.includes(e.code)) {
      trashDirFault = ensureTrashDir();
      if (!trashDirFault) return moveToTrash(filename, true);
    }
    return { error: trashErrorMessage('Không dời được ảnh vào thùng rác.', e) };
  }
  return { ok: true };
}

// The way back. Anything the bin does not hold is simply skipped, which covers a
// file trashed before its derivative was ever generated. Same rollback rule as
// the way in: a restore that dies halfway must not leave the image split across
// the two trees.
function restoreFromTrash(filename, retried = false) {
  if (trashDirFault) trashDirFault = ensureTrashDir();

  const done = [];
  const undo = () => {
    for (const [from, back] of done.reverse()) {
      try {
        moveOne(from, back);
      } catch {
        /* best effort */
      }
    }
  };

  try {
    for (const full of filePaths(filename)) {
      const src = trashPathFor(full);
      if (!src || !fs.existsSync(src)) continue;
      moveOne(src, full);
      done.push([full, src]);
    }
  } catch (e) {
    console.error('[media] không khôi phục được ảnh từ thùng rác:', filename, e && e.code, e && e.message);
    undo();
    if (!retried && PERMISSION_CODES.includes(e.code)) {
      trashDirFault = ensureTrashDir();
      if (!trashDirFault) return restoreFromTrash(filename, true);
    }
    return { error: trashErrorMessage('Không khôi phục được ảnh từ thùng rác.', e) };
  }
  return { ok: true };
}

// Unlinks every copy of an upload, in the served tree and in the bin. Used by
// purge, where nothing may survive, and by pruneMissingFiles(), where a
// derivative left behind in either place would sit forever.
function removeEveryCopy(filename) {
  for (const full of filePaths(filename)) {
    for (const p of [full, trashPathFor(full)]) {
      if (!p) continue;
      try {
        fs.unlinkSync(p);
      } catch {
        /* absent is not an error */
      }
    }
  }
}

// ---------------------------------------------------------------- disk space

// Free bytes on the filesystem holding the uploads, or null when it cannot be
// determined (statfs is not available on every platform - Windows during local
// development, notably). A null reading must NOT block an upload: failing closed
// here would make the library unusable on a machine where the check simply does
// not work.
function freeDiskBytes() {
  try {
    if (typeof fs.statfsSync !== 'function') return null;
    const st = fs.statfsSync(PUBLIC_UPLOAD_DIR);
    return st.bavail * st.bsize;
  } catch {
    return null;
  }
}

// The single limit an admin is held to. Checked before the body is read, so a
// caller is refused before the server spends the disk, and again after the file
// lands - a large upload can consume the headroom while it is being written.
function diskHeadroomError(incomingBytes = 0) {
  const free = freeDiskBytes();
  if (free === null) return null;
  if (free - incomingBytes < MIN_FREE_DISK_BYTES) {
    const gb = (free / (1024 * 1024 * 1024)).toFixed(2);
    return `Đĩa máy chủ chỉ còn ${gb} GB trống. Hãy xoá bớt ảnh cũ trong Thư viện trước khi tải lên tiếp.`;
  }
  return null;
}

// ---------------------------------------------------------------- validation

// Turns a file that has landed in TMP_UPLOAD_DIR into a permanent one in
// public/uploads, or deletes it and returns an error.
//
// The order matters and is the whole point: the bytes are inspected while the file
// is still outside the served directory, so a rejected upload is never reachable
// over HTTP even for the moment before it is deleted.
function commitUpload({ tmpPath, originalName, uploaderId, isAdmin, folderId = null }) {
  const discard = () => {
    try {
      fs.unlinkSync(tmpPath);
    } catch {
      /* already gone */
    }
  };

  let stat;
  try {
    stat = fs.statSync(tmpPath);
  } catch {
    return { error: 'Không đọc được file đã tải lên.' };
  }
  if (stat.size === 0) {
    discard();
    return { error: 'File tải lên rỗng.' };
  }

  const head = readHead(tmpPath);
  const sniffed = sniffFormat(head);
  if (!sniffed) {
    discard();
    return { error: 'File này không phải ảnh JPG, PNG, WEBP hoặc GIF hợp lệ.' };
  }

  // The extension written to disk comes from the CONTENT, not from the name the
  // client sent, so a mismatch cannot be used to choose how the file is served.
  // .jpeg and .jpg are the same format; keep whichever the caller used.
  const claimed = path.extname(String(originalName || '')).toLowerCase();
  const ext = sniffed === '.jpg' && claimed === '.jpeg' ? '.jpeg' : sniffed;

  // Re-checked after the write: a long upload can have eaten the headroom that
  // was available when it started.
  const diskError = diskHeadroomError();
  if (diskError) {
    discard();
    return { error: diskError };
  }

  const filename = generateFilename(ext);
  const target = path.join(PUBLIC_UPLOAD_DIR, filename);
  try {
    fs.renameSync(tmpPath, target);
  } catch (e) {
    // EXDEV: the two directories turned out to be on different filesystems after
    // all (a bind mount, a separate volume for data/). Fall back to a copy.
    if (e.code === 'EXDEV') {
      try {
        fs.copyFileSync(tmpPath, target);
        discard();
      } catch (copyError) {
        discard();
        return { error: 'Không lưu được ảnh trên máy chủ.' };
      }
    } else {
      discard();
      return { error: 'Không lưu được ảnh trên máy chủ.' };
    }
  }

  const size = imageSize(head, ext);
  const row = insertMedia({
    filename,
    originalName: decodeOriginalName(originalName || filename).slice(0, 255),
    mimeType: MIME_BY_EXT[ext] || 'application/octet-stream',
    bytes: stat.size,
    width: size ? size.width : null,
    height: size ? size.height : null,
    uploaderId,
    // Files land in whichever folder the uploader had open, so uploading into a
    // folder does not mean uploading and then moving.
    folderId: folderId !== null && getFolder(folderId) ? Number(folderId) : null,
  });

  // The grid shows the thumbnail, not this file. Generated in the background:
  // the upload itself is already answered as soon as the original is on disk,
  // and if ImageMagick is absent ensureThumb is a no-op that resolves false.
  thumbs.ensureThumb(filename).catch(() => {});

  return { media: row, url: `/uploads/${filename}`, unlimited: isAdmin };
}

